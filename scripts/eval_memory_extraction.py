NOTE = MEMORY_TYPE_NOTE


@dataclass(frozen=True)
class Case:
    """One turn and what the pipeline should make of it.

    Expectations are about *shape and routing*, never about wording. Asserting on
    exact sentences would make the eval fail every time the model rephrased
    something harmlessly, and the wording of a fact or episode is generated by the
    application anyway.
    """

    name: str
    user: str
    assistant: str = "Understood."

    # Each entry is (memory_type, label) where label is a fact's memory_key, a
    # note's category, or None to accept any label of that type.
    expected: tuple[tuple[str, str | None], ...] = ()

    # Shapes that must NOT appear. This is where routing regressions show up: a
    # preference leaking into the free tier is a real fault even though something
    # was remembered.
    forbidden: tuple[tuple[str, str | None], ...] = ()

    # Nothing at all should be stored.
    expect_nothing: bool = False

    # Set for cases where remembering anything is a policy failure, so a run can
    # report those separately from ordinary misses.
    is_safety: bool = False

    # The time window a stored note should carry, when the turn stated one. Checked
    # against the window only, never against a resolved date: the model's job is to
    # classify and the application's job is to calculate, so a date here would be
    # testing the wrong component.
    expected_time_reference: str | None = None

    notes: str = ""


