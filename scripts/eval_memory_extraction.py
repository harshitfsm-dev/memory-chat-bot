"""Evaluate what the memory extractor actually remembers from a turn.

Run it:

    uv run python scripts/eval_memory_extraction.py
    uv run python scripts/eval_memory_extraction.py --repeat 3 --verbose

Why this exists
---------------
Extraction quality is invisible in normal use. A worse extractor does not raise,
does not log an error, and does not fail a request — the assistant just quietly
remembers the wrong things, or stops remembering the right ones. That failure mode
gets much easier to hit once the memory tier accepts free text, because the model
is no longer confined to a closed vocabulary it either matches or does not.

So this measures the pipeline against fixed expectations. Run it before and after
changing the extraction prompt, the model, the category list, or the storage
filters. The absolute score matters less than whether it moved.

What it measures
----------------
The *stored* outcome, not the raw model output: every candidate goes through the
same normalization the application uses, so what you see here is what would end up
in the database. A note the privacy filter rejects counts as not remembered, which
is the honest accounting.

Two things it cannot tell you: whether retrieval later surfaces a memory at the
right moment, and whether a wrong memory actually changed an answer.

Needs Ollama running. Needs no database — extraction and normalization never touch
one, which is why the service is built here with no repository.
"""

